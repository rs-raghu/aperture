import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const packageRoot = path.resolve(import.meta.dirname, "..");
const calculatorsRoot = path.join(packageRoot, "src", "calculators");
const outputPath = path.join(calculatorsRoot, "calculator.registry.generated.ts");

function pluginFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return pluginFiles(entryPath);
    return entry.name.endsWith(".plugin.ts") ? [entryPath] : [];
  });
}

const modules = pluginFiles(calculatorsRoot).sort().map((filePath) => {
  const source = fs.readFileSync(filePath, "utf8");
  const match = /export const (\w+Plugin) =/.exec(source);
  if (!match?.[1]) throw new Error(`Calculator plug-in export not found in ${filePath}`);
  const modulePath = `./${path.relative(calculatorsRoot, filePath).replaceAll("\\", "/").replace(/\.ts$/, ".js")}`;
  return { modulePath, variable: match[1] };
});

const output = `/* This file is generated by scripts/generate-calculator-registry.mjs. Do not edit directly. */
${modules.map(({ modulePath, variable }) => `import { ${variable} } from "${modulePath}";`).join("\n")}

${modules.map(({ modulePath }) => `export * from "${modulePath}";`).join("\n")}

export const allFinanceCalculatorPlugins = Object.freeze([
${modules.map(({ variable }) => `  ${variable},`).join("\n")}
]);

const calculatorIds = new Set(allFinanceCalculatorPlugins.map((plugin) => plugin.manifest.id));
if (calculatorIds.size !== allFinanceCalculatorPlugins.length) throw new Error("Finance calculator identifiers must be unique.");

export const investmentCalculatorPlugins = Object.freeze(allFinanceCalculatorPlugins.filter((plugin) => plugin.manifest.category === "investment"));
export const loanCalculatorPlugins = Object.freeze(allFinanceCalculatorPlugins.filter((plugin) => plugin.manifest.category === "loan"));
export const incomeTaxCalculatorPlugins = Object.freeze(allFinanceCalculatorPlugins.filter((plugin) => plugin.manifest.category === "income_tax"));
export const economicCalculatorPlugins = Object.freeze(allFinanceCalculatorPlugins.filter((plugin) => plugin.manifest.category === "economic"));
export const retirementCalculatorPlugins = Object.freeze(allFinanceCalculatorPlugins.filter((plugin) => plugin.manifest.category === "retirement"));

export function getFinanceCalculatorPlugin(id: string) {
  return allFinanceCalculatorPlugins.find((plugin) => plugin.manifest.id === id);
}

export function getInvestmentCalculatorPlugin(id: string) {
  return investmentCalculatorPlugins.find((plugin) => plugin.manifest.id === id);
}

export function getRetirementCalculatorPlugin(id: string) {
  return retirementCalculatorPlugins.find((plugin) => plugin.manifest.id === id);
}
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error("Finance calculator registry is out of date. Run npm run generate --workspace @aperture/finance.");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated registry for ${modules.length} Finance calculator plug-ins.`);
}
