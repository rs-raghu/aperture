import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const packageRoot = path.resolve(import.meta.dirname, "..");
const sourceRoot = path.join(packageRoot, "src", "calculators", "investments");
const outputPath = path.join(sourceRoot, "investment.registry.generated.ts");

const modules = fs.readdirSync(sourceRoot)
  .filter((name) => name.endsWith(".plugin.ts"))
  .sort()
  .map((fileName) => {
    const source = fs.readFileSync(path.join(sourceRoot, fileName), "utf8");
    const match = /export const (\w+Plugin) =/.exec(source);
    if (!match?.[1]) throw new Error(`Investment plug-in export not found in ${fileName}`);
    return { fileName: fileName.replace(/\.ts$/, ".js"), variable: match[1] };
  });

const imports = modules.map(({ fileName, variable }) => `import { ${variable} } from "./${fileName}";`).join("\n");
const exports = modules.map(({ fileName }) => `export * from "./${fileName}";`).join("\n");
const entries = modules.map(({ variable }) => `  ${variable},`).join("\n");
const output = `/* This file is generated by scripts/generate-investment-registry.mjs. Do not edit directly. */
${imports}

${exports}

export const investmentCalculatorPlugins = Object.freeze([
${entries}
]);

const investmentCalculatorIds = new Set(investmentCalculatorPlugins.map((plugin) => plugin.manifest.id));
if (investmentCalculatorIds.size !== investmentCalculatorPlugins.length) {
  throw new Error("Investment calculator identifiers must be unique.");
}

export function getInvestmentCalculatorPlugin(id: string) {
  return investmentCalculatorPlugins.find((plugin) => plugin.manifest.id === id);
}
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error("Investment calculator registry is out of date. Run npm run generate --workspace @aperture/finance.");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated registry for ${modules.length} investment calculator plug-ins.`);
}
